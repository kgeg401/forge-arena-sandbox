"""Verify Emry's own mechanics through real rules inputs in a normal match."""
import json
from emry_test_client import EmryGame,EMRY,BOMB,ORNITHOPTER,TAP,DRAW,BOUNCE

g=EmryGame()
try:
    g.lands(3);g.ensure_hand(ORNITHOPTER);g.ensure_hand(BOMB);emry=g.ensure_hand(EMRY)
    g.check('Zero artifacts: Emry costs2U',g.cost(emry)==[{'color':'Generic','count':2},{'color':'Blue','count':1}])
    orn=g.one('hand',ORNITHOPTER);g.cast(orn)
    g.check('One artifact: Emry costs1U',g.cost(emry)==[{'color':'Generic','count':1},{'color':'Blue','count':1}])
    bomb=g.one('hand',BOMB);g.cast(bomb)
    g.check('Two artifacts: Emry costsU',g.cost(emry)==[{'color':'Blue','count':1}])
    before=g.tapped_lands();g.cast(emry,False)
    g.check('Real discounted cast pays exactly one blue land',g.tapped_lands()-before==1)
    g.step();trigger=next(a for a in g.s['stackAbilities'] if a['sourceForgeId']==emry['forgeId'])
    g.check('Entry creates the source-bound mill trigger',trigger['triggered'] and trigger['abilityId']==86971)
    lib={c['forgeId'] for c in g.s['hidden'] if c['owner']==1 and c['zone']=='Library'}
    gy={c['forgeId'] for c in g.s['graveyard']};other={c['forgeId'] for c in g.s['hidden'] if c['owner']==2}
    g.resolve();milled=[c for c in g.cards('graveyard') if c['forgeId'] not in gy]
    after={c['forgeId'] for c in g.s['hidden'] if c['owner']==1 and c['zone']=='Library'}
    g.check('Mill removes exactly four actual own-library instances',len(lib-after)==4 and {c['forgeId'] for c in milled}==lib-after)
    g.check('Mill does not change opponent hidden zones',other=={c['forgeId'] for c in g.s['hidden'] if c['owner']==2})
    g.check('Summoning sickness prevents tap ability',not any(a['abilityId']==TAP for a in g.s['legalActivations']))
    g.reject('Cannot activate Emry while summoning sick','activate_ability',emry['forgeId'],abilityId=TAP)
    g.next_main();g.optional_land()
    g.check('A later untap permits Emry activation',any(a['abilityId']==TAP for a in g.s['legalActivations']))
    g.reject('Activation identity cannot be a coerced string','activate_ability',emry['forgeId'],abilityId=str(TAP))
    g.reject('Activation identity cannot be fractional','activate_ability',emry['forgeId'],abilityId=TAP+0.5)
    g.reject('Activation identity must be supplied','activate_ability',emry['forgeId'])
    g.activation(g.one('battlefield',BOMB),DRAW);target=g.one('graveyard',BOMB)
    g.check('Artifact cannot be cast from graveyard without permission',target['forgeId'] not in g.s['legalCasts'])
    g.send('activate_ability',emry['forgeId'],abilityId=TAP)
    d=g.s['decision'];offered={o['forgeId'] for o in d['options']}
    expected={c['forgeId'] for c in g.cards('graveyard') if c['name'] in (BOMB,ORNITHOPTER)}
    g.check('Emry offers exactly own graveyard artifacts',offered==expected)
    g.reject('Stale target token is rejected','select_targets',decisionToken='stale',assignments=[{'forgeId':target['forgeId']}])
    g.reject('Other player cannot choose Emry target','select_targets',decisionToken=d['token'],seat=2,assignments=[{'forgeId':target['forgeId']}])
    g.reject('A hand card cannot be supplied as a graveyard target','select_targets',decisionToken=d['token'],assignments=[{'forgeId':g.one('hand','Island')['forgeId']}])
    g.send('cancel_targets',decisionToken=d['token'])
    g.check('Cancel before payment leaves Emry untapped',not next(c for c in g.cards('battlefield',EMRY) if c['forgeId']==emry['forgeId'])['tapped'])
    g.activation(emry,TAP,target,False)
    g.check('Tap cost is paid on the real source',next(c for c in g.cards('battlefield',EMRY) if c['forgeId']==emry['forgeId'])['tapped'])
    g.check('Activated ability retains exact target',any(a['abilityId']==TAP and a['targetForgeIds']==[target['forgeId']] for a in g.s['stackAbilities']))
    g.reject('Permission is not granted before ability resolves','cast_spell',target['forgeId']);g.resolve()
    g.check('Resolved permission offers selected artifact',target['forgeId'] in g.s['legalCasts'])
    g.check('Other graveyard artifacts remain unavailable',not any(c['forgeId'] in g.s['legalCasts'] for c in g.cards('graveyard') if c['forgeId']!=target['forgeId']))
    g.check('Permission does not waive artifact mana cost',g.cost(target)==[{'color':'Generic','count':1}])
    before=g.tapped_lands();g.cast(target)
    g.check('Graveyard cast really pays one mana',g.tapped_lands()-before==1)
    g.activation(g.one('battlefield',BOMB),DRAW)
    g.check('A newly returned graveyard object needs new permission',target['forgeId'] not in g.s['legalCasts'])
    g.reject('Tapped Emry cannot grant another permission','activate_ability',emry['forgeId'],abilityId=TAP)
    g.next_main();g.optional_land();target=g.one('graveyard',BOMB);g.activation(emry,TAP,target)
    g.check('Untapped Emry can grant permission again',target['forgeId'] in g.s['legalCasts'])
    g.next_main();g.optional_land()
    g.check('Unused permission expires at end of turn',target['forgeId'] not in g.s['legalCasts'])
    spare=g.ensure_hand(BOMB);g.lands(6);g.cast(spare);g.activation(emry,TAP,target)
    g.activation(spare,BOUNCE,emry,False)
    g.check('Noninstant artifact obeys stack timing',target['forgeId'] not in g.s['legalCasts']);g.resolve()
    g.check('Emry actually moved to hand',any(c['forgeId']==emry['forgeId'] for c in g.cards('hand',EMRY)))
    g.check('Permission survives Emry leaving battlefield',target['forgeId'] in g.s['legalCasts'])
    g.cast(target)
    g.check('Artifact cast succeeds after Emry leaves',any(c['forgeId']==target['forgeId'] for c in g.cards('battlefield',BOMB)))
    result=dict(checks=len(g.e.checks),evidence=str(g.e.ipc),turn=g.s['turn'],scope='Normal Match.startGame and public adapter inputs; no intermediate state injection or native rendering claim')
    (g.e.ipc/'emry-result.json').write_text(json.dumps(result,indent=2));print(json.dumps(result,indent=2))
finally:g.close()
