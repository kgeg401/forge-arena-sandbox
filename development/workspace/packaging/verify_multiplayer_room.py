"""Two real HTTP clients; fixture views/actions test transport, not Magic rules."""
import copy,json,threading,uuid,urllib.request
from concurrent.futures import ThreadPoolExecutor
from multiplayer_room import Room,RoomClient,RoomServer,RoomError,decode

checks=[]
def check(name,ok):assert ok,name;checks.append(name)
def rejects(name,call,status=None):
    try:call()
    except (RoomError,ValueError) as error:check(name,status is None or getattr(error,'status',None)==status)
    else:raise AssertionError(name)

compat=dict(native='fixture-native-sha',rules='fixture-rules-sha',catalogue='fixture-catalogue-sha')
room=Room(compat);server=RoomServer(room);thread=threading.Thread(target=server.serve_forever,daemon=True);thread.start()
url='http://127.0.0.1:'+str(server.server_port);host=RoomClient(url,room.host_token);joiner=RoomClient(url,room.invite)
try:
    check('No socket listens on public interfaces',server.server_address[0]=='127.0.0.1')
    check('Host waits for an actual second client',host.call('/v1/state')['phase']=='waiting-for-player')
    rejects('Invitation cannot read host state',lambda:joiner.call('/v1/state'),401)
    join=dict(id=str(uuid.uuid4()),protocol=1,compatibility=compat)
    rejects('Mismatched client build cannot join',lambda:joiner.call('/v1/join',{**join,'compatibility':dict(native='other')}),409)
    reply=joiner.call('/v1/join',join);guest=RoomClient(url,reply['token'])
    check('Second process receives only its own player role',reply['player']==2 and guest.call('/v1/state')['player']==2)
    check('Dropped join response can be retried idempotently',joiner.call('/v1/join',join)==reply)
    rejects('Invitation cannot admit a third player',lambda:joiner.call('/v1/join',{**join,'id':str(uuid.uuid4())}),409)
    session=str(uuid.uuid4());views={1:dict(session=session,viewerSeat=1,hand=['private-A'],hidden=[dict(id=22)],public=['board']),2:dict(session=session,viewerSeat=2,hand=['private-B'],hidden=[dict(id=11)],public=['board'])}
    room.publish(session,views,2,'decision-2');views[1]['hand'].append('mutated-after-publish')
    a=host.call('/v1/state');b=guest.call('/v1/state')
    for key in ('randomSeed','opponentDeck','researchTrace'):
        rejects('Network views refuse private metadata: '+key,lambda key=key:room.publish(session,{1:{**views[1],key:'secret'},2:views[2]},2,'decision-2'))
    check('Each HTTP client receives only its own private view',a['state']['hand']==['private-A'] and b['state']['hand']==['private-B'] and 'private-B' not in json.dumps(a) and 'private-A' not in json.dumps(b))
    check('A published view is not aliased to caller-owned data','mutated-after-publish' not in a['state']['hand'])
    action=dict(id=str(uuid.uuid4()),session=session,revision=b['revision'],decisionToken='decision-2',action=dict(op='submit_choice',assignments=[dict(choiceId=7)]))
    rejects('Player cannot act for the other priority owner',lambda:host.call('/v1/command',action),409)
    rejects('Player cannot forge a seat field',lambda:guest.call('/v1/command',{**action,'seat':1}),400)
    rejects('Client cannot change the authoritative match',lambda:guest.call('/v1/command',{**action,'session':str(uuid.uuid4())}),409)
    rejects('Old board revisions cannot accept new actions',lambda:guest.call('/v1/command',{**action,'revision':b['revision']-1}),409)
    rejects('Boolean revisions are not integer revisions',lambda:guest.call('/v1/command',{**action,'revision':True}),409)
    rejects('Old decisions cannot accept new actions',lambda:guest.call('/v1/command',{**action,'decisionToken':'stale'}),409)
    rejects('Debug/snapshot and file operations are not remote commands',lambda:guest.call('/v1/command',{**action,'action':dict(op='load-file',path='secret')}),400)
    rejects('Noncanonical command IDs cannot become Windows filenames',lambda:guest.call('/v1/command',{**action,'id':'urn:uuid:'+action['id']}),400)
    rejects('Boolean game object identities are refused',lambda:guest.call('/v1/command',{**action,'action':dict(op='cast_spell',forgeId=True)}),400)
    rejects('Invalid assignment containers are refused',lambda:guest.call('/v1/command',{**action,'action':dict(op='submit_choice',assignments={'choiceId':7})}),400)
    with ThreadPoolExecutor(max_workers=2) as pool:receipts=list(pool.map(lambda _:guest.call('/v1/command',action),range(2)))
    check('Concurrent duplicate input queues once without claiming engine acceptance',receipts[0]==receipts[1] and receipts[0]['status']=='queued' and 'accepted' not in receipts[0])
    rejects('Queued input cannot silently acquire another board or choice',lambda:room.publish(session,views,1))
    command=room.take_command()
    check('Authenticated role supplies the authoritative input seat',command['seat']==2 and command['action']==action['action'])
    check('The rules consumer cannot dispatch the same queued input twice',room.take_command() is None)
    rejects('A reused command ID cannot carry a different choice',lambda:guest.call('/v1/command',{**action,'action':dict(op='concede')}),409)
    rejects('A second distinct action waits for the pending result',lambda:guest.call('/v1/command',{**action,'id':str(uuid.uuid4())}),409)
    rejects('Rules result must own the pending command',lambda:room.complete(1,command['id'],True,'wrong owner'))
    room.complete(2,command['id'],False,'Fixture chooser rejected stale card')
    done=guest.call('/v1/command',action)
    check('Actual rules rejection remains a rejection across reconnect/retry',done['status']=='completed' and done['accepted'] is False and room.take_command() is None)
    rejects('Next input waits for a new authoritative view',lambda:guest.call('/v1/command',{**action,'id':str(uuid.uuid4())}),409)
    room.publish(session,{1:{**views[1],'hand':['private-A']},2:views[2]},1)
    h=host.call('/v1/state');fresh=dict(id=str(uuid.uuid4()),session=session,revision=h['revision'],decisionToken=None,action=dict(op='pass_priority'))
    room.seen[2]-=31
    rejects('A missing peer pauses new input without inventing a pass',lambda:host.call('/v1/command',fresh),409)
    reconnected=RoomClient(url,reply['token']).call('/v1/state')
    check('Reconnect retains the same match and revision',reconnected['session']==session and reconnected['revision']==h['revision'])
    host.call('/v1/command',fresh);room.seen[2]-=31
    check('An already queued input is held while its peer is absent',room.take_command() is None)
    guest.call('/v1/state');check('The held input resumes once after peer reconnect',room.take_command()['id']==fresh['id'] and room.take_command() is None)
    rejects('An active room cannot silently reset to a new match',lambda:room.publish(str(uuid.uuid4()),views,1))
    rejects('Public HTTP room URLs are refused',lambda:RoomClient('http://example.com',room.host_token))
    rejects('Credential/query-bearing invite URLs are refused',lambda:RoomClient('https://user@example.com/?token=secret',room.host_token))
    rejects('Duplicate JSON fields are rejected',lambda:decode(b'{"seat":1,"seat":2}'))
    request=urllib.request.Request(url+'/v1/state',headers={'Authorization':'Bearer '+room.host_token,'Origin':'https://foreign.example'})
    try:urllib.request.urlopen(request)
    except urllib.error.HTTPError as error:check('Browser-origin requests cannot borrow native room access',error.code==403)
    else:raise AssertionError('Origin not rejected')
    room.close();rejects('Closed rooms reject retained tokens',lambda:guest.call('/v1/state'),410)
finally:server.shutdown();server.server_close();thread.join(timeout=5)
print(json.dumps(dict(passed=True,checks=len(checks),results=checks,scope=__doc__),indent=2))
